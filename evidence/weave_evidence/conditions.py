def cite(key: str, prototype_dir: str = "inventory-proof") -> str:
    """The quotation followed by its citation. Producer docstrings are cited in ``prototype_dir``."""
    path, section, quote = CONDITIONS[key]
    if path.startswith("inventory-proof/"):
        path = prototype_dir + path[len("inventory-proof"):]
    return f"{quote} [{path}, {section}]"


def conditions(kind: str, prototype_dir: str = "inventory-proof") -> list[str]:
    return [cite(key, prototype_dir) for key in KINDS[kind]]
